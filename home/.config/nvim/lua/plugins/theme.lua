-- bg=none skips the background escape entirely, so foot just shows its own
-- default bg for these cells -- which is what its alpha-mode=matching treats
-- as transparent (an explicit hex here, even one identical in value, won't
-- match). Merged onto each group's own table so fg/other attrs survive.
local transparent = {
  'Normal', 'NormalNC', 'NormalFloat',
  'FloatBorder', 'TelescopeNormal', 'TelescopeBorder',
  'SignColumn', 'FoldColumn', 'EndOfBuffer',
  'WinSeparator', 'WinBar', 'WinBarNC', 'TabLine', 'TabLineFill',
}

return {
  { 'rakibdev/material-colors', subdir = 'lua', lazy = false, priority = 1001 },
  {
    dir      = '/home/rakib/Downloads/material-code/nvim',
    name     = 'material-code',
    lazy     = false,
    priority = 1000,
    config   = function()
      local materialCode = require('material-code')
      -- generated by `theme` CLI (system-ui): border/hover come pre-stripped
      -- of alpha ({var.hex} in templates/nvim.lua) since terminals can't
      -- composite it; blend()'d back against background below.
      local colorsPath = vim.fn.expand('~/.config/nvim/lua/colors.lua')
      -- darkMode isn't part of the color palette, only theme.json has it
      local themeJsonPath = vim.fn.expand('~/.config/system-ui/theme.json')

      -- intentionally lower than generate.cppm's 0.10: our blend() bakes
      -- against a flat background reference instead of the real blurred
      -- backdrop GTK composites against, so the same alpha reads brighter
      -- here than in glass GTK surfaces
      local glassAlpha = 0.02

      local function readJson(path)
        local f = io.open(path)
        if not f then return {} end
        local data = vim.json.decode(f:read('*a'))
        f:close()
        return data or {}
      end

      local function applyTheme()
        local ok, colors = pcall(dofile, colorsPath)
        if not ok or not colors then return end
        local dark = readJson(themeJsonPath).darkMode ~= false

        colors.border  = materialCode.blend(colors.border, colors.background, glassAlpha)
        colors.hover   = materialCode.blend(colors.hover, colors.background, glassAlpha)
        colors.card    = materialCode.blend(colors.card, colors.background, glassAlpha)
        colors.popover = colors.background

        local syntax = materialCode.createSyntaxColors(colors.primary, dark)
        colors = vim.tbl_extend('force', colors, { syntax = syntax, darkMode = dark })

        local highlights = materialCode.createNeovimTheme(colors)
        for _, group in ipairs(transparent) do
          highlights[group] = vim.tbl_extend('force', highlights[group] or {}, { bg = 'none' })
        end

        materialCode.apply(highlights, dark)
        vim.api.nvim_exec_autocmds('ColorScheme', { pattern = 'material-code' })
      end

      applyTheme()
      local watcher = vim.uv.new_fs_event()
      watcher:start(colorsPath, {}, function(err, _, events)
        if err or not events.change then return end
        vim.defer_fn(applyTheme, 100)
      end)
    end,
  },
}
